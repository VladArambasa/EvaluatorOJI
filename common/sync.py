#!/usr/bin/env python3
# SYNC SHARED FILES INTO THE VERSIONS; RUN AFTER ANY CHANGE IN COMMON/
# COPIES THE GUI, PROBES AND RUNNER; REGENERATES THE EMBEDDED HEADERS FOR C AND C++
import os
import shutil

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
RES = [("EMB_GUI", "common/gui/index.html"), ("EMB_PROBE_C", "common/probe/olieval_probe.c"),
       ("EMB_PROBE_PY", "common/probe/sitecustomize.py")]
COPIES = [
    ("common/gui/index.html", ["versions/python/index.html", "versions/web/public/index.html"]),
    ("common/probe/olieval_probe.c", ["versions/python/olieval_probe.c", "versions/web/olieval_probe.c"]),
    ("common/probe/sitecustomize.py", ["versions/python/sitecustomize.py", "versions/web/sitecustomize.py"]),
    ("common/runner/runner.c", ["versions/web/helper/runner.c", "versions/c/src/runner.c"]),
    ("common/runner/runner.h", ["versions/web/helper/runner.h", "versions/c/src/runner.h"]),
    ("common/runner/olieval_run.c", ["versions/web/helper/olieval_run.c"]),
]


def gen():
    # ONE BYTE ARRAY PER RESOURCE, ZERO-TERMINATED
    out = ["/* GENERATED BY COMMON/SYNC.PY - DO NOT EDIT */",
           "#ifndef OLIEVAL_EMBEDDED_H", "#define OLIEVAL_EMBEDDED_H"]
    for name, rel in RES:
        data = open(os.path.join(ROOT, rel), "rb").read()
        out.append("static const unsigned char %s[] = {" % name)
        for i in range(0, len(data), 24):
            out.append("    " + ",".join("0x%02x" % b for b in data[i:i + 24]) + ",")
        out.append("    0x00};")
        out.append("static const unsigned long %s_LEN = %dUL;" % (name, len(data)))
    out.append("#endif")
    return "\n".join(out) + "\n"


for src, dests in COPIES:
    for d in dests:
        p = os.path.join(ROOT, d)
        os.makedirs(os.path.dirname(p), exist_ok=True)
        shutil.copyfile(os.path.join(ROOT, src), p)
        print("copied", src, "->", d)

text = gen()
for dest in ("versions/c++/src/embedded.hpp", "versions/c/src/embedded.h"):
    p = os.path.join(ROOT, dest)
    with open(p, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("written", dest, len(text.encode("utf-8")), "bytes")
