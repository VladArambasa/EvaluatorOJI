def students_of(prob):
    d = os.path.join(ROOT, prob)
    return sorted(x for x in os.listdir(d) if os.path.isdir(os.path.join(d, x)) and not x.startswith(("_", ".")))


def layout_ws(**changes):
    cfg = json.loads(json.dumps(ws))
    cfg.update(changes)
